function cleanupFixture({ shutdownError = false, survivor = false, groupOnly = false, removeFails = false, remains = false } = {}) {
  let swept = false, rootPresent = true;
  const calls = [];
  return { calls, ops: {
    shutdown: async () => { calls.push('shutdown'); if (shutdownError) throw Error('stub shutdown exception'); },
    snapshot: () => ({ owned: (survivor || remains) && (!swept || remains) ? [123] : [], groups: groupOnly && !swept ? [{ pgid: 456, members: [{ pid: 457 }] }] : [] }),
    fallback: async () => { calls.push('fallback'); swept = true; },
    removeRoot: () => { calls.push('remove'); if (!removeFails) rootPresent = false; },
    rootExists: () => rootPresent,
  } };
}
test('orderly shutdown plus empty snapshots and verified root absence passes', async () => {
  const f = cleanupFixture(); const result = await verifyCleanup(f.ops);
  assert.equal(result.orderly, true); assert.deepEqual(f.calls, ['shutdown', 'remove']);
  assert.equal(result.rootRemoved, true);
});
for (const [name, options] of Object.entries({
  'shutdown exception': { shutdownError: true },
  'survivor cleaned by fallback': { survivor: true },
  'surviving group without marked PID list': { groupOnly: true },
  'root remains after removal': { removeFails: true },
  'fallback cannot empty owned processes': { survivor: true, remains: true },
  'reviewer shutdown exception plus surviving group': { shutdownError: true, survivor: true, groupOnly: true },
})) test(`cleanup cannot green: ${name}`, async () => {
  const f = cleanupFixture(options); const result = await verifyCleanup(f.ops);
  assert.equal(result.orderly, false);
  assert(result.errors.length > 0);
  if (options.survivor || options.groupOnly) assert(f.calls.includes('fallback'), 'safe fallback still runs');
});
test('snapshot errors cannot skip safe fallback or become green', async () => {
  const f = cleanupFixture(); f.ops.snapshot = () => { throw Error('stub observation error'); };
  const result = await verifyCleanup(f.ops);
  assert.equal(result.orderly, false); assert(f.calls.includes('fallback'));
});
